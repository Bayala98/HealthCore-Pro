-- Estas tablas conservan los nombres/columnas esperados por la aplicación.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT UNIQUE, correo TEXT UNIQUE, password TEXT,
    nombre TEXT, apellido TEXT, edad INTEGER, genero TEXT, estatura DOUBLE PRECISION,
    peso DOUBLE PRECISION, meta_tipo TEXT, meta_kg DOUBLE PRECISION,
    avatar_path TEXT, avatar_category TEXT, avatar_name TEXT, theme TEXT
);
CREATE TABLE IF NOT EXISTS health_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tipo TEXT NOT NULL, valor DOUBLE PRECISION, detalle TEXT,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL, operation TEXT NOT NULL, record_id BIGINT,
    user_id BIGINT, occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    summary TEXT
);

-- Trigger combinado: toda escritura de health_records genera una fila de auditoría.
CREATE OR REPLACE FUNCTION audit_health_record_change() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE r health_records;
BEGIN
    IF TG_OP = 'DELETE' THEN r := OLD; ELSE r := NEW; END IF;
    INSERT INTO audit_log(table_name, operation, record_id, user_id, summary)
    VALUES ('health_records', TG_OP, r.id, r.user_id, r.tipo);
    RETURN r;
END; $$;
DROP TRIGGER IF EXISTS trg_health_record_audit ON health_records;
CREATE TRIGGER trg_health_record_audit
AFTER INSERT OR UPDATE OR DELETE ON health_records
FOR EACH ROW EXECUTE FUNCTION audit_health_record_change();

-- Función de base de datos para calcular IMC; devuelve NULL para entradas no válidas.
CREATE OR REPLACE FUNCTION calculate_bmi(weight_kg DOUBLE PRECISION, height_m DOUBLE PRECISION)
RETURNS DOUBLE PRECISION LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT CASE WHEN height_m > 0 AND weight_kg > 0
      THEN ROUND((weight_kg / (height_m * height_m))::numeric, 2)::double precision
      ELSE NULL END;
$$;

-- Procedimiento de inserción; el INSERT activa automáticamente el trigger anterior.
CREATE OR REPLACE PROCEDURE register_health_record(
    p_user_id BIGINT, p_tipo TEXT, p_valor DOUBLE PRECISION, p_detalle TEXT
)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_tipo IS NULL OR btrim(p_tipo) = '' THEN
        RAISE EXCEPTION 'El tipo de registro es obligatorio';
    END IF;
    INSERT INTO health_records(user_id, tipo, valor, detalle)
    VALUES (p_user_id, btrim(p_tipo), p_valor, p_detalle);
END; $$;

